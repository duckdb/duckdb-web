class _Annotation:
    """Prints a string annotation as written, without the quotes inspect adds."""

    def __init__(self, text):
        self.text = text

    def __repr__(self):
        return self.text


def nanobind_signature_line(obj, name):
    """The signature nanobind writes as the first docstring line of a C++ function."""
    if type(obj).__module__ != "nanobind":
        return None
    first = (inspect.getdoc(obj) or "").split("\n", 1)[0]
    return first if first.startswith(f"{name}(") else None


def member_signature(obj, name):
    if line := nanobind_signature_line(obj, name):
        return line
    try:
        signature = inspect.signature(obj)
    except (TypeError, ValueError):
        return None
    parameters = [
        (
            p.replace(annotation=_Annotation(p.annotation))
            if isinstance(p.annotation, str)
            else p
        )
        for p in signature.parameters.values()
    ]
    returns = signature.return_annotation
    if isinstance(returns, str):
        returns = _Annotation(returns)
    return name + str(
        signature.replace(parameters=parameters, return_annotation=returns)
    )


def unwrap(paragraph):
    """Join the hard-wrapped lines of a prose paragraph; leave lists and code as written."""
    lines = paragraph.splitlines()
    if any(re.match(r"\s*([-*>]|\d+\.)\s|\s{4}|\s*```", line) for line in lines):
        return paragraph
    return " ".join(line.strip() for line in lines)


def member_description(obj, name):
    doc = inspect.getdoc(obj) or ""
    if nanobind_signature_line(obj, name):
        doc = doc.split("\n", 1)[1] if "\n" in doc else ""
    return "\n\n".join(unwrap(p) for p in doc.strip().split("\n\n"))


def returns_relation(obj, name):
    if line := nanobind_signature_line(obj, name):
        return "DuckDBPyRelation" in line.rsplit("->", 1)[-1]
    try:
        returns = inspect.signature(obj).return_annotation
    except (TypeError, ValueError):
        return False
    return "DuckDBPyRelation" in str(returns)


def run_example(code):
    """Return the example's output, and its error output when it failed or wrote to stderr."""
    with tempfile.TemporaryDirectory() as workdir:
        try:
            proc = subprocess.run(
                [sys.executable, "-I", "-c", EXAMPLE_RUNNER],
                input=code,
                capture_output=True,
                text=True,
                cwd=workdir,
                timeout=600,
            )
        except subprocess.TimeoutExpired:
            return "", "timed out after 600 seconds"
    failed = proc.returncode != 0 or proc.stderr.strip()
    return proc.stdout.strip("\n"), proc.stderr.strip() if failed else None


def example_code(member_details):
    code = member_details.example.strip("\n")
    if member_details.use_default_example:
        return DEFAULT_EXAMPLE.format(code_example=code)
    return code


def collect_members():
    members = []
    seen = {}
    for section, section_details in SECTION_MAP.items():
        for method_list in section_details["method_list"]:
            cls = method_list["class"]
            for name in method_list["members"]:
                anchor = name
                if name in seen:
                    seen[name] += 1
                    anchor = f"{name}-{seen[name]}"
                else:
                    seen[name] = 0
                obj = getattr(cls, name)
                is_property = isinstance(inspect.getattr_static(cls, name), property)
                description = member_description(obj, name)
                members.append(
                    {
                        "section": section,
                        "class": cls,
                        "name": name,
                        "anchor": anchor,
                        "signature": (
                            None if is_property else member_signature(obj, name)
                        ),
                        "description": description,
                        "details": DOCS_DETAILS_MAP.get(anchor, PythonRelAPIDetails()),
                    }
                )
    return members


def alias_text(member):
    """The pointer an alias entry shows; a deprecated alias, by its docstring, says so."""
    details = member["details"]
    target = re.sub(r"-\d+$", "", details.alias_of)
    if not isinstance(inspect.getattr_static(member["class"], target, None), property):
        target += "()"
    kind = (
        "Deprecated alias"
        if member["description"].startswith("Deprecated")
        else "Alias"
    )
    return f"{kind} of [`{target}`](#{details.alias_of})."


def render_member(member, result):
    details = member["details"]
    parts = [f"### `{member['name']}`"]
    if member["signature"]:
        parts.append(f"```python\n{member['signature']}\n```")
    if details.alias_of:
        parts.append(alias_text(member) + details.additional_description)
        return "\n\n".join(parts)
    parts.append(f"{member['description']}{details.additional_description}")
    if details.aliases:
        parts.append(
            "**Aliases**: "
            + ", ".join(f"[`{alias}`](#{alias})" for alias in details.aliases)
        )
    if details.parameters:
        parts.append(
            "**Parameters**\n\n"
            + "\n".join(
                f"* **{p.parameter_name}** : {', '.join(p.parameter_type)}"
                + (f", default: {p.parameter_default}" if p.parameter_default else "")
                + "\n\n"
                + textwrap.indent(p.parameter_description, "    ")
                for p in details.parameters
            )
        )
    if details.example:
        parts.append(
            "**Example**\n\n"
            + PLACEHOLDER_EXAMPLE.format(code_example=example_code(details))
        )
    if result:
        parts.append(
            "**Result**\n\n"
            + PLACEHOLDER_RESULT.format(result=result, result_type=details.result_type)
        )
    return "\n\n".join(parts)


INTRODUCTION_EXAMPLE = re.compile(r"```python\n(.*?)\n```\n\n```text\n.*?\n```", re.S)


def render_introduction():
    """Run each introduction example and write its output in the text block after it."""
    failures = []

    def captured(match):
        output, error = run_example(match.group(1))
        if error is not None:
            failures.append(error)
        return f"```python\n{match.group(1)}\n```\n\n```text\n{output}\n```"

    text = INTRODUCTION_EXAMPLE.sub(captured, INTRODUCTION_TEXT)
    if failures:
        raise SystemExit(
            "An introduction example did not run cleanly:\n" + "\n\n".join(failures)
        )
    return text


def toc_row(member):
    if member["details"].alias_of:
        return f"| [`{member['name']}`](#{member['anchor']}) | {alias_text(member)} |"
    first_paragraph = member["description"].split("\n\n", 1)[0].replace("\n", " ")
    first_paragraph = first_paragraph.replace("|", "\\|")
    return f"| [`{member['name']}`](#{member['anchor']}) | {first_paragraph} |"


def write_page(introduction, members, results):
    with open(f"docs/{DUCKDB_DOC_VERSION}/clients/python/relational_api.md", "w") as f:
        f.write(FORMATTER_TEXT)
        f.write("\n")
        f.write(introduction)
        f.write("\n")
        for section, section_details in SECTION_MAP.items():
            in_section = [m for m in members if m["section"] == section]
            f.write(f"\n\n## {section} \n\n")
            f.write(section_details["description"])
            f.write("\n\n| Name | Description |\n|:--|:-------|\n")
            f.write("\n".join(toc_row(m) for m in in_section))
            f.write("\n\n")
            f.write(
                "\n\n----\n\n".join(
                    render_member(m, results.get(m["anchor"])) for m in in_section
                )
            )
        f.write("\n")


def check_fully_documented(class_name, configured_in_script, class_members):
    problems = []
    if gone := sorted(set(configured_in_script) - set(class_members)):
        problems.append(f"members that {class_name} no longer has: {gone}")
    if undocumented := sorted(set(class_members) - set(configured_in_script)):
        problems.append(
            f"members of {class_name} that no section lists: {undocumented}"
        )
    if twice := sorted(
        {m for m in configured_in_script if configured_in_script.count(m) > 1}
    ):
        problems.append(f"members of {class_name} listed more than once: {twice}")
    return problems


def generate_python_relational_api_md():
    relation_members = [
        name
        for name, _ in inspect.getmembers(duckdb.DuckDBPyRelation)
        if not name.startswith("_")
    ]
    problems = check_fully_documented(
        "DuckDBPyRelation",
        PY_RELATION_MEMBERS + list(UNDOCUMENTED_RELATION_MEMBERS),
        relation_members,
    )
    problems += check_fully_documented(
        "DuckDBPyConnection",
        CREATION_MEMBER_LIST,
        [
            name
            for name, obj in inspect.getmembers(duckdb.DuckDBPyConnection)
            if not name.startswith("_") and returns_relation(obj, name)
        ],
    )
    if problems:
        raise SystemExit(
            "The relational API member lists are out of date:\n" + "\n".join(problems)
        )

    members = collect_members()
    with_examples = [
        m for m in members if m["details"].example and not m["details"].alias_of
    ]
    with ThreadPoolExecutor(max_workers=os.cpu_count()) as pool:
        runs = list(
            pool.map(lambda m: run_example(example_code(m["details"])), with_examples)
        )
    failures = [
        f"{m['anchor']}:\n{error}"
        for m, (_, error) in zip(with_examples, runs)
        if error is not None
    ]
    if failures:
        raise SystemExit(
            f"{len(failures)} examples did not run cleanly:\n\n" + "\n\n".join(failures)
        )
    introduction = render_introduction()
    write_page(
        introduction,
        members,
        {m["anchor"]: output for m, (output, _) in zip(with_examples, runs)},
    )


if __name__ == "__main__":
    generate_python_relational_api_md()
