INTRODUCTION_TEXT = """
The Relational API builds a query one step at a time from Python.
A relation, a `DuckDBPyRelation`, is a piece of SQL text: the methods of the [Transformation](#transformation) and [Functions](#functions) sections return a new relation whose text extends the one they were called on.

## Lazy Evaluation

Building a relation runs nothing: DuckDB binds the text once to learn the columns and their types, and holds no data.
For example, a relation over a billion rows is built at once:

```python
import duckdb

duckdb_conn = duckdb.connect()

rel = duckdb_conn.sql("FROM range(1_000_000_000) t(id) SELECT id, id % 7 AS bucket")
print(rel.sql_query())
```

```text
FROM range(1_000_000_000) t(id) SELECT id, id % 7 AS bucket
```

[`sql_query()`](#sql_query) returns exactly the text that runs.
The query runs when a method of the [Output](#output) section reads the relation, and it runs again on every read, so each read sees the current data.
Printing a relation, or calling [`show()`](#show), also runs it and displays the first rows:

```python
import duckdb

duckdb_conn = duckdb.connect()
rel = duckdb_conn.sql("FROM range(1_000_000_000) t(id) SELECT id, id % 7 AS bucket")
rel.filter("bucket = 3").order("id").limit(3).show()
```

```text
┌───────┬────────┐
│  id   │ bucket │
│ int64 │ int64  │
├───────┼────────┤
│     3 │      3 │
│    10 │      3 │
│    17 │      3 │
└───────┴────────┘
```

Only a statement that reads, such as a `SELECT`, gives a lazy relation.
Any other statement passed to [`sql()`](#sql), such as `CREATE TABLE` or `INSERT`, runs at the call, and the relation holds what it returned.
The `params` list or dict is copied when the relation is created, and its values are converted each time the relation runs.
A column is also an attribute of the relation, as in `rel.price`, unless a method has its name: a column called `offset` is reached as `rel["offset"]`, since `rel.offset` is the [`offset()`](#offset) method.

To run a query once and keep its rows, call [`materialize()`](#materialize):

```python
import duckdb

duckdb_conn = duckdb.connect()
duckdb_conn.sql("CREATE TABLE items (id INTEGER)")
counted = duckdb_conn.sql("SELECT count(*) AS n FROM items")
held = counted.materialize()
duckdb_conn.sql("INSERT INTO items VALUES (1), (2)")
print(counted.fetchall(), held.fetchall())
```

```text
[(2,)] [(0,)]
```
"""

