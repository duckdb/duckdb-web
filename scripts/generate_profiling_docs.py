import argparse
import json
import os
import subprocess
from pathlib import Path

from tabulate import tabulate

REPO_ROOT = Path(__file__).resolve().parents[1]
METRICS_DOC_PATH = REPO_ROOT / "docs" / "2.0" / "dev" / "metrics.md"
METRICS_DOC_TEMPLATE = REPO_ROOT / "scripts" / "metrics.md.template"

METRICS_MARKER = "<!-- METRICS -->"

GROUP_DESCRIPTIONS = {
    "query": "Metrics measured over the entire query.",
    "system": "Metrics on system resources, such as memory and threads, used while running the query.",
    "io": "Metrics on the data read from and written to storage.",
    "storage": "Metrics on storage operations, such as attaching databases, writing to the WAL and checkpointing.",
    "operator": "Metrics collected for each individual operator in the query plan. These are reported in the `operator` tree of the profiling output.",
    "optimizer": "Metrics measuring the time spent in the [optimizers]({% link docs/2.0/internals/overview.md %}#optimizer).",
    "parser": "Metrics on parsing the SQL query.",
    "planner": "Metrics on generating the logical plan.",
    "physical_planner": "Metrics on generating the physical plan.",
}


def load_metrics(db_path):
    # we pass /dev/null to the initialization script to skip reading `~/.duckdbrc`
    env = {k: v for k, v in os.environ.items() if k not in ("AI_AGENT", "CLAUDECODE")}
    res = subprocess.run(
        [
            db_path,
            "-init",
            os.devnull,
            "-json",
            "-c",
            "FROM duckdb_available_metrics()",
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        check=True,
    )
    return json.loads(res.stdout.decode('utf8'))


def main():
    parser = argparse.ArgumentParser(
        description="Generate documentation for DuckDB profiling metrics based on duckdb_available_metrics()"
    )
    parser.add_argument(
        "--duckdb-binary",
        required=True,
        type=str,
        help="Path to the DuckDB CLI binary",
    )
    args = parser.parse_args()

    metrics = load_metrics(args.duckdb_binary)
    groups = {}
    for metric in metrics:
        group = metric["metric_name"].split(".")[0]
        groups.setdefault(group, []).append(metric)

    template = METRICS_DOC_TEMPLATE.read_text()
    if METRICS_MARKER not in template:
        raise SystemExit(f"Could not find {METRICS_MARKER} in {METRICS_DOC_TEMPLATE}")
    before, after = template.split(METRICS_MARKER)

    out = before.rstrip("\n") + "\n\n"
    out += (
        "<!-- This section is generated by scripts/generate_profiling_docs.py -->\n\n"
    )
    out += "## All Metrics\n\n"
    out += "The metrics are organized into the following groups:\n\n"
    for group in groups:
        out += f"* [`{group}`](#{group}-metrics)\n"

    for group, group_metrics in groups.items():
        out += f"\n### `{group}` Metrics\n\n"
        out += GROUP_DESCRIPTIONS.get(group, "") + "\n\n"
        if group == "optimizer":
            per_optimizer = [
                m for m in group_metrics if m["metric_name"] != "optimizer.total_time"
            ]
            group_metrics = [
                m for m in group_metrics if m["metric_name"] == "optimizer.total_time"
            ]
        rows = [
            [
                f"`{m['metric_name']}`",
                f"`{m['metric_type']}`",
                m["unit"] or "",
                m["description"],
            ]
            for m in group_metrics
        ]
        out += tabulate(
            rows, headers=["Name", "Type", "Unit", "Description"], tablefmt="github"
        )
        out += "\n"
        if group == "optimizer":
            out += (
                "\nAdditionally, each optimizer has a corresponding metric that follows the template "
                "`optimizer.⟨optimizer_name⟩` and measures the time (in seconds) spent in that optimizer. "
                "These metrics are only collected when the specific optimizer is enabled. "
                "The available optimizers can be queried using the "
                "[`duckdb_optimizers()`{:.language-sql .highlight} table function]"
                "({% link docs/2.0/sql/meta/duckdb_table_functions.md %}#duckdb_optimizers):\n\n"
            )
            out += ", ".join(f"`{m['metric_name']}`" for m in per_optimizer) + ".\n"

    out += "\n" + after.lstrip("\n")
    METRICS_DOC_PATH.write_text(out)


if __name__ == "__main__":
    main()
